import { expect, it } from "vitest";
import type { Issue } from "./index.js";
import { renderHookInputTypes } from "./index.js";

const HEADER = "// Generated by claude-code-hook-types from the hooks template. Do not edit.";
const EMPTY = `${HEADER}\nexport interface McpToolHookInputs {}\n`;

// A template whose hooks.PreToolUse[0].hooks are the given hooks.
const preToolUse = (...hooks: unknown[]): object => ({
  hookTypes: "hook-types.d.ts",
  hooks: { PreToolUse: [{ matcher: "Bash", hooks }] },
});

const mcp = (input: unknown, server: unknown = "s", tool: unknown = "t"): object => ({
  type: "mcp_tool",
  server,
  tool,
  input,
});

// Expected source with one server "s" and one tool "t" of the given type.
const single = (type: string): string =>
  `${HEADER}\nexport interface McpToolHookInputs {\n  "s": {\n    "t": ${type};\n  };\n}\n`;

const inputIssue = (path: readonly (string | number)[], message: string): Issue => ({
  severity: "error",
  code: "hook-input-invalid",
  message,
  path,
});

it.each([null, [], "x"])("reports the non-object template %j", (template) => {
  expect(renderHookInputTypes(template)).toEqual({
    source: "",
    issues: [
      {
        severity: "error",
        code: "template-invalid",
        message: `template ${JSON.stringify(template)}: must be an object`,
      },
    ],
  });
});

it("renders an empty interface without mcp_tool hooks", () => {
  expect(renderHookInputTypes({})).toEqual({ source: EMPTY, issues: [] });
  expect(renderHookInputTypes({ hooks: "x" })).toEqual({ source: EMPTY, issues: [] });
});

it("ignores hooks that are not mcp_tool and malformed groups", () => {
  const template = {
    hooks: {
      PreToolUse: [
        { hooks: [{ type: "command", command: "echo" }, { type: "http", url: "https://example.com" }, "x", null] },
        { matcher: "Bash" },
        "x",
      ],
      Stop: "x",
    },
  };
  expect(renderHookInputTypes(template)).toEqual({ source: EMPTY, issues: [] });
});

it("infers literal types for strings, numbers, booleans, null, objects and arrays", () => {
  const input = { s: "a", n: 1.5, b: false, z: null, o: { y: [1, "x"], x: {} }, e: [] };
  expect(renderHookInputTypes(preToolUse(mcp(input)))).toEqual({
    source: single(`{ "b": false; "e": []; "n": 1.5; "o": { "x": {}; "y": [1, "x"] }; "s": "a"; "z": null }`),
    issues: [],
  });
  expect(renderHookInputTypes(preToolUse(mcp({}))).source).toBe(single("{}"));
});

it("widens strings with ${...} substitutions to string", () => {
  const input = { p: "${tool_input.file_path}", q: "pre-${a}-post", r: "$notsub", t: "{plain}" };
  expect(renderHookInputTypes(preToolUse(mcp(input))).source).toBe(
    single(`{ "p": string; "q": string; "r": "$notsub"; "t": "{plain}" }`),
  );
});

it("sorts servers, tools and keys", () => {
  const template = preToolUse(
    mcp({ b: 1, a: 2 }, "srv-b", "tool-z"),
    mcp({}, "srv-b", "tool-y"),
    mcp({}, "srv-a", "tool-x"),
  );
  expect(renderHookInputTypes(template).source).toBe(
    [
      HEADER,
      "export interface McpToolHookInputs {",
      `  "srv-a": {`,
      `    "tool-x": {};`,
      "  };",
      `  "srv-b": {`,
      `    "tool-y": {};`,
      `    "tool-z": { "a": 2; "b": 1 };`,
      "  };",
      "}",
      "",
    ].join("\n"),
  );
});

it("joins distinct shapes of one server and tool into a sorted union and drops duplicates", () => {
  const template = {
    hooks: {
      PreToolUse: [{ hooks: [mcp({ a: 2 }), mcp({ a: 1 })] }],
      PostToolUse: [{ hooks: [mcp({ a: 1 })] }],
    },
  };
  expect(renderHookInputTypes(template)).toEqual({ source: single(`{ "a": 1 } | { "a": 2 }`), issues: [] });
});

it("reports invalid mcp_tool hooks with their path and skips them", () => {
  const template = preToolUse(
    { type: "mcp_tool", server: "s", tool: "t" },
    mcp([1]),
    mcp({ a: 1 }, 1),
    mcp({ a: 1 }, "s", ""),
    mcp({ ok: true }),
  );
  const at = (index: number, field: string): readonly (string | number)[] => [
    "hooks",
    "PreToolUse",
    0,
    "hooks",
    index,
    field,
  ];
  expect(renderHookInputTypes(template)).toEqual({
    source: single(`{ "ok": true }`),
    issues: [
      inputIssue(at(0, "input"), "hooks.PreToolUse[0].hooks[0].input undefined: must be an object"),
      inputIssue(at(1, "input"), "hooks.PreToolUse[0].hooks[1].input [1]: must be an object"),
      inputIssue(at(2, "server"), "hooks.PreToolUse[0].hooks[2].server 1: must be a string"),
      inputIssue(at(3, "tool"), `hooks.PreToolUse[0].hooks[3].tool "": must be a string`),
    ],
  });
});

it("renders the mcp-hook fixture template exactly", () => {
  const template = {
    mod: "./src/register.ts",
    hookTypes: "src/hook-types.d.ts",
    hooks: {
      PreToolUse: [{
        matcher: "Write|Edit",
        hooks: [{
          type: "mcp_tool",
          server: "plugin:mcp-hook:checker",
          tool: "check_path",
          input: { path: "${tool_input.file_path}", strict: true },
        }],
      }],
      PostToolUse: [{
        matcher: "Write",
        hooks: [{
          type: "mcp_tool",
          server: "plugin:mcp-hook:checker",
          tool: "check_path",
          input: { path: "${tool_input.file_path}", tags: ["post", 1] },
        }],
      }],
    },
  };
  expect(renderHookInputTypes(template)).toEqual({
    source: [
      HEADER,
      "export interface McpToolHookInputs {",
      `  "plugin:mcp-hook:checker": {`,
      `    "check_path": { "path": string; "strict": true } | { "path": string; "tags": ["post", 1] };`,
      "  };",
      "}",
      "",
    ].join("\n"),
    issues: [],
  });
});
